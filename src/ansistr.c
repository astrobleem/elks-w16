static u32 codepage_string(u16 ss,u16 ap,const u8 *map)
{
 u16 a,b,as,bs,firsta,firstb;u8 c;
 if(ap>0xfff8u)return 0;
 a=firsta=AW(4);as=AW(6);b=firstb=AW(0);bs=AW(2);
 for(;;){
  if(!readable(as,a)||!readable(bs,b))return 0;
  c=rd8(as,a);if(!c)break;
  if(a==0xffffu||b==0xffffu)return 0;
  a++;b++;
 }
 /* A partial overlap could overwrite the unread terminator. Exact physical
  * aliases are safe; reject other overlapping spans before any write. */
 {u32 pa=((u32)as<<4)+firsta,pb=((u32)bs<<4)+firstb,n=(u32)a-firsta+1;
  if(pa!=pb&&pa<pb+n&&pb<pa+n)return 0;
 }
 a=firsta;b=firstb;
 for(;;){c=rd8(as,a);wr8(bs,b,map[c]);if(!c)break;a++;b++;}
 return 1;
}
